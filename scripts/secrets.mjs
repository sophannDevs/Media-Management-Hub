// The key that encrypts stored OAuth tokens (SEC-04, src/lib/secrets.ts).
//   node scripts/secrets.mjs key      prints a new "id:key" entry for TOKEN_ENCRYPTION_KEYS
//   node scripts/secrets.mjs ensure   adds TOKEN_ENCRYPTION_KEYS to .env when it is missing
//                                     (run by `npm run dev`, so development always has one)
// Rotation: put a new entry FIRST in TOKEN_ENCRYPTION_KEYS, keep the old one,
// run `npm run secrets:rotate`, then drop the old entry.
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const NAME = "TOKEN_ENCRYPTION_KEYS";
const newKey = (id = "k1") => `${id}:${randomBytes(32).toString("base64url")}`;

const command = process.argv[2] ?? "key";
if (command === "key") {
  console.log(newKey(process.argv[3] ?? `k${Date.now().toString(36)}`));
} else if (command === "ensure") {
  if (process.env[NAME]) process.exit(0);
  const text = existsSync(".env") ? readFileSync(".env", "utf8") : "";
  const has = text.split(/\r?\n/).some((l) => new RegExp(`^\\s*${NAME}\\s*=\\s*\\S`).test(l));
  if (has) process.exit(0);
  const eol = text.includes("\r\n") ? "\r\n" : "\n";
  const block = [
    "",
    "# Encrypts stored OAuth tokens (generated by `npm run dev`; `npm run secrets:key` makes another).",
    "# Rotation: add a new entry first, keep the old one, run `npm run secrets:rotate`, then drop the old one.",
    `${NAME}="${newKey()}"`,
    "",
  ].join(eol);
  writeFileSync(".env", (text.endsWith(eol) || text === "" ? text : text + eol) + block);
  console.log(`Added ${NAME} to .env (stored OAuth tokens are encrypted with it; keep it with your backups).`);
} else {
  console.error(`Unknown command "${command}". Use key or ensure.`);
  process.exit(1);
}
